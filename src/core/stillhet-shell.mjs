// src/core/stillhet-shell.mjs — the server-side render of the Stillhet shell (ui/public/stillhet/shell.html), the
// page the server sends in place of index.html when the `rail` flag is on. Pure, like index-html.mjs: the server
// hands in the file text, the theme mode, the interface level and whether git is usable.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { INDEX_THEME_ANCHOR } from './index-html.mjs';

export const STILLHET_SHELL = 'ui/public/stillhet/shell.html';
// The shell is a template: every spelling static maps to it (a path relative to ui/public) is served only through
// sendIndex, with its page and headers, flag on or off.
export const isStillhetShellRel = (rel) => /^stillhet\/shell(\.html)?$/i.test(rel ?? '');

/**
 * @param {string} html  the on-disk ui/public/stillhet/shell.html
 * @param {'system'|'light'|'dark'} theme
 * @param {'simple'|'advanced'|'expert'} [level]
 * @param {{ git?: boolean, adapter?: 'live'|'demo', railLocked?: boolean }} [opts]  railLocked: `rail` is locked by WORCA_FLAGS, so
 *   the top-bar Stillhet UI switch is drawn disabled and says why (docs/rail/navigation.md nav.design-switch)  adapter: which data the pages read (ui/public/stillhet/adapter.js);
 *   live unless the server runs with WORCA_STILLHET_DEMO=1 (the pixel comparison and the gates, docs/feature-flags.md)
 * @returns {string}
 * @throws {Error} 'stillhet shell anchor missing' when the theme anchor is gone
 */
export function renderStillhetShell(html, theme, level, { git, adapter = 'live', railLocked = false } = {}) {
  if (!html.includes(INDEX_THEME_ANCHOR)) throw new Error('stillhet shell anchor missing');
  const lvl = level ? ` data-level="${level}"` : '';
  const gitAttr = typeof git === 'boolean' ? ` data-git="${git ? 'on' : 'off'}"` : '';
  const data = adapter === 'demo' ? 'demo' : 'live';
  return html.replace(INDEX_THEME_ANCHOR, `<html lang="en" data-theme="${theme}"${lvl}${gitAttr} data-adapter="${data}"${railLocked ? ' data-rail-locked="true"' : ''}>`);
}

// Generated by tools/stillhet-build.mjs, gitignored in ui/public/stillhet/, shipped in the package.
export const STILLHET_BUNDLES = ['components.js', 'graph.js', 'app.css'];

/** The generated files missing from `<publicDir>/stillhet/`. */
export const missingStillhetBundles = (publicDir) => STILLHET_BUNDLES.filter((f) => !existsSync(path.join(publicDir, 'stillhet', f)));

// The build tool is a source-checkout file (tools/ is not in the package), so it is named in two pieces and never as two
// literal join() segments: the related-tests graph (tools/test-related.mjs) must not read this as an edge from ui/server.mjs
// to the CSS assembler the tool uses. Relative to this file and to the public dir alike (both sit two levels below the root).
const BUILD_TOOL = '../../tools/' + 'stillhet-build.mjs';

// What the bundles are built from, relative to the public dir: a bundle older than any of these is stale.
const BUNDLE_SOURCES = ['design-system/components', 'stillhet/graph', 'style.css', '../../docs/design-system-catalog.json'];
const newest = (p) => {
  let st; try { st = statSync(p); } catch { return 0; }
  return st.isDirectory() ? Math.max(0, ...readdirSync(p).map((n) => newest(path.join(p, n)))) : st.mtimeMs;
};

/**
 * The generated files that must be (re)built: missing ones everywhere, and in a source checkout (where tools/ sits beside
 * the public dir) also those older than their sources, so a pull never leaves a stale bundle served.
 */
export function staleStillhetBundles(publicDir) {
  const missing = missingStillhetBundles(publicDir);
  if (missing.length) return missing;
  if (!existsSync(path.join(publicDir, BUILD_TOOL))) return [];
  const src = Math.max(...BUNDLE_SOURCES.map((s) => newest(path.join(publicDir, s))));
  return STILLHET_BUNDLES.filter((f) => statSync(path.join(publicDir, 'stillhet', f)).mtimeMs < src);
}

let building = null;   // concurrent first requests share one build

/**
 * The page the server sends when `rail` is on. The generated files are checked here, on the first such request and never at
 * start-up: a source checkout builds what is missing or stale; an installed package only reports the missing file.
 * @throws {Error} naming the missing file when it cannot be built
 */
export async function stillhetShellHtml(publicDir, theme, level, git, { railLocked = false } = {}) {
  if (staleStillhetBundles(publicDir).length) {
    building ||= import(BUILD_TOOL).then((m) => m.buildStillhet()).finally(() => { building = null; });
    try { await building; }
    catch (err) { throw new Error(`ui/public/stillhet/${staleStillhetBundles(publicDir)[0] || 'components.js'} is missing: ${err.message}`); }
  }
  return renderStillhetShell(readFileSync(path.join(publicDir, 'stillhet', 'shell.html'), 'utf8'), theme, level, { git, adapter: process.env.WORCA_STILLHET_DEMO === '1' ? 'demo' : 'live', railLocked });
}
