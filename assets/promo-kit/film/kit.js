/* kit.js — the promo film's runtime. One paused GSAP master timeline; the only clock is F.seek(t).
   Read promo-kit/CONTRACT.md before writing a scene. Globals: F (this kit), gsap, Mascot (mascot.js),
   FILM_DATA (data.js, generated by tools/build-data.mjs from promo/timeline.json + promo/plates/manifest.json). */
(function () {
  'use strict';
  const D = window.FILM_DATA;
  const W = 1920, H = 1080, FPS = 60;
  const ROOT = '../';                       // film/ sits in the promo dir; manifest plate files are relative to it
  const F = window.F = {
    W, H, FPS, D, DUR: D.layout.duration,
    master: gsap.timeline({ paused: true }),
    scenes: [], hooks: [], cues: [], violations: [], pending: new Set(), images: new Set(),
    t: 0,
  };
  gsap.ticker.lagSmoothing(0);
  const SVGNS = 'http://www.w3.org/2000/svg';
  const violation = (msg) => { if (!F.violations.includes(msg)) { F.violations.push(msg); console.warn('[film] ' + msg); } };
  F.violation = violation;

  /* ---------- DOM helpers ---------- */
  function el(tag, opts = {}) {
    const e = tag === 'svg' || opts.svg ? document.createElementNS(SVGNS, tag) : document.createElement(tag);
    if (opts.cls) e.setAttribute('class', opts.cls);
    if (opts.style) Object.assign(e.style, opts.style);
    if (opts.attrs) for (const [k, v] of Object.entries(opts.attrs)) e.setAttribute(k, v);
    if (opts.html != null) e.innerHTML = opts.html;
    if (opts.text != null) e.textContent = opts.text;
    if (opts.parent) opts.parent.appendChild(e);
    return e;
  }
  F.el = el;

  /** Set an <img> source and register its decode so seek() waits for it. */
  function setSrc(img, url) {
    if (img.__src === url) return;
    img.__src = url;
    img.src = url;
    const p = img.decode().catch(() => violation('image failed to decode: ' + url)).finally(() => F.pending.delete(p));
    F.pending.add(p);
  }
  F.setSrc = setSrc;
  F.plateUrl = (file) => ROOT + file;

  /* ---------- stage ---------- */
  const stage = document.getElementById('stage');
  const scenesLayer = el('div', { cls: 'f-scenes', parent: stage });
  F.stage = stage; F.scenesLayer = scenesLayer;

  /* ---------- VO lookup ---------- */
  const norm = (s) => String(s).toLowerCase().replace(/[^a-z0-9-]/g, '');
  F.vo = (id) => { const v = D.vo[id]; if (!v) { violation('unknown VO line ' + id); return { start: 0, end: 0, words: [] }; } return v; };
  /** Absolute start (or end with edge='t1') of the nth occurrence of word `key` in VO line `id`. */
  F.word = (id, key, nth = 1, edge = 't0') => {
    const v = F.vo(id); const k = norm(key); let n = 0;
    for (const w of v.words) if (w.key === k && ++n === nth) return w[edge];
    // prefix match as a fallback ("clarify" matches "clarify." already; this catches "test" → "test-first")
    n = 0;
    for (const w of v.words) if (w.key.startsWith(k) && ++n === nth) return w[edge];
    violation(`word "${key}" #${nth} not in ${id}: ${v.text}`);
    return v.start;
  };

  /* ---------- SFX cues ---------- */
  F.SFX = ['whoosh', 'whoosh-short', 'swoosh-up', 'swish-down', 'pop', 'pop-high', 'bubble', 'click', 'tap', 'type',
    'boing', 'thud', 'squash', 'ding', 'success', 'sparkle', 'stamp', 'slide', 'zip', 'tick', 'step', 'hop', 'land',
    'snore', 'alarm', 'scratch', 'drumroll', 'confetti', 'lock', 'buzz', 'cash', 'chime', 'rise', 'impact', 'wobble', 'blip'];
  /** Record a sound cue at absolute time t. gain 0..1.5, pan -1..1. `dur` only for looped kinds (type, drumroll, snore). */
  F.sfxAt = (t, name, o = {}) => {
    if (!F.SFX.includes(name)) violation('unknown sfx ' + name);
    F.cues.push({ t: +t.toFixed(4), name, gain: o.gain ?? 1, pan: o.pan ?? 0, dur: o.dur ?? null, rate: o.rate ?? 1 });
  };

  /* ---------- plates ---------- */
  class Plate {
    constructor(S, name, state, o = {}) {
      const meta = D.plates[name];
      this.S = S; this.name = name; this.meta = meta;
      if (!meta) { violation('unknown plate ' + name); }
      const st = meta && (meta.states[state] || Object.values(meta.states)[0]);
      if (meta && !meta.states[state]) violation(`plate ${name} has no state ${state}`);
      this.w = st ? st.w : 400; this.h = st ? st.h : 240;
      const scale = o.scale ?? (o.w ? o.w / this.w : 1);
      this.scale = scale;
      this.el = el('div', { cls: 'f-plate' + (o.cls ? ' ' + o.cls : ''), parent: o.parent || S.world,
        style: { width: this.w + 'px', height: this.h + 'px' } });
      this.el.dataset.plate = name;
      this.imgs = {};
      this.cur = state;
      if (st) this._img(state, 1);
      const origin = o.origin || 'center';
      const ox = origin === 'center' ? this.w / 2 : 0, oy = origin === 'center' ? this.h / 2 : 0;
      this.ox = ox; this.oy = oy;
      this.x = o.x ?? W / 2; this.y = o.y ?? H / 2;
      gsap.set(this.el, { x: this.x - ox, y: this.y - oy, scale, transformOrigin: `${ox}px ${oy}px`, force3D: false });
      if (o.hidden) gsap.set(this.el, { autoAlpha: 0 });
    }
    _img(state, opacity = 0) {
      if (this.imgs[state]) return this.imgs[state];
      const st = this.meta && this.meta.states[state];
      if (!st) { violation(`plate ${this.name} has no state ${state}`); return null; }
      const img = el('img', { cls: 'f-plate-img', parent: this.el, attrs: { alt: '', draggable: 'false' },
        style: { width: st.w + 'px', height: st.h + 'px', opacity } });
      setSrc(img, ROOT + st.file);
      F.images.add(img);
      this.imgs[state] = img;
      return img;
    }
    /** Crossfade to another captured state at local time `at`. dur 0 = hard switch. */
    show(at, state, dur = 0.18) {
      const to = this._img(state); if (!to) return this;
      const from = Object.entries(this.imgs).filter(([k]) => k !== state).map(([, v]) => v);
      if (dur <= 0) { this.S.tl.set(to, { opacity: 1 }, at); if (from.length) this.S.tl.set(from, { opacity: 0 }, at); }
      else { this.S.tl.to(to, { opacity: 1, duration: dur, ease: 'none' }, at); if (from.length) this.S.tl.to(from, { opacity: 0, duration: dur, ease: 'none' }, at + dur * 0.5); }
      return this;
    }
    /** Step through states at a fixed interval (typing captures, progress states). */
    steps(at, states, interval = 0.06) { states.forEach((s, i) => this.show(at + i * interval, s, 0)); return this; }
    /** Anchor rect centre in WORLD coordinates for the plate's placed position/scale (no later tweens). */
    anchor(name, ax = 0.5, ay = 0.5) {
      const a = this.meta && this.meta.anchors && this.meta.anchors[name];
      if (!a) { violation(`plate ${this.name} has no anchor ${name}`); return { x: this.x, y: this.y, w: 0, h: 0 }; }
      const lx = a.x + a.w * ax, ly = a.y + a.h * ay;
      return { x: this.x + (lx - this.ox) * this.scale, y: this.y + (ly - this.oy) * this.scale, w: a.w * this.scale, h: a.h * this.scale };
    }
    /** Plate bounds in WORLD coordinates for the placed geometry. */
    bounds() { const s = this.scale; return { x: this.x - this.ox * s, y: this.y - this.oy * s, w: this.w * s, h: this.h * s }; }
  }

  /** A frame sequence from a plate's `seqs` entry, flipped deterministically from the film clock. */
  class Seq {
    constructor(S, name, seqName, o = {}) {
      const meta = D.plates[name]; const sq = meta && meta.seqs && meta.seqs[seqName];
      this.S = S; this.sq = sq;
      if (!sq) violation(`plate ${name} has no seq ${seqName}`);
      this.w = sq ? sq.w : 400; this.h = sq ? sq.h : 240;
      const scale = o.scale ?? (o.w ? o.w / this.w : 1);
      this.scale = scale;
      this.el = el('div', { cls: 'f-plate f-seq', parent: o.parent || S.world, style: { width: this.w + 'px', height: this.h + 'px' } });
      this.img = el('img', { cls: 'f-plate-img', parent: this.el, attrs: { alt: '' }, style: { width: this.w + 'px', height: this.h + 'px' } });
      F.images.add(this.img);
      const origin = o.origin || 'center';
      this.ox = origin === 'center' ? this.w / 2 : 0; this.oy = origin === 'center' ? this.h / 2 : 0;
      this.x = o.x ?? W / 2; this.y = o.y ?? H / 2;
      gsap.set(this.el, { x: this.x - this.ox, y: this.y - this.oy, scale, transformOrigin: `${this.ox}px ${this.oy}px`, force3D: false });
      this.spans = [];
      if (sq) this._frame(0);
      S.onFrame((t) => {
        if (!this.sq) return;
        let idx = null;
        for (const sp of this.spans) if (t >= sp.at) idx = sp.idx(t);
        this._frame(idx == null ? 0 : idx);
      });
    }
    _frame(i) {
      const sq = this.sq; const n = sq.count;
      const k = Math.max(0, Math.min(n - 1, i));
      setSrc(this.img, ROOT + sq.dir + '/' + String(k).padStart(4, '0') + '.png');
    }
    /** From local time `at`, play frames [from, to) at `fps` (default the seq's fps); loop → wrap, else hold the last. */
    play(at, o = {}) {
      const sq = this.sq || { count: 1, fps: 30 };
      const fps = o.fps ?? sq.fps ?? 30, from = o.from ?? 0, to = o.to ?? sq.count, loop = !!(o.loop ?? sq.loop);
      const n = Math.max(1, to - from);
      this.spans.push({ at, idx: (t) => { const k = Math.floor((t - at) * fps + 1e-6); return from + (loop ? ((k % n) + n) % n : Math.min(k, n - 1)); } });
      return this;
    }
    hold(at, frame) { this.spans.push({ at, idx: () => frame }); return this; }
  }

  /* ---------- camera ---------- */
  class Camera {
    constructor(S) {
      this.S = S; this.p = { x: W / 2, y: H / 2, lz: 0, r: 0 };
      S.onFrame(() => {
        const z = Math.exp(this.p.lz);
        S.world.style.transform = `translate(${W / 2 - this.p.x * z}px, ${H / 2 - this.p.y * z}px) scale(${z}) rotate(${this.p.r}deg)`;
      });
    }
    /** Move so world point (x,y) sits at the stage centre with `zoom`, over `dur` seconds from local `at`. */
    to(at, { x, y, zoom, rot }, dur = 0.8, ease = 'power3.inOut') {
      const v = {};
      if (x != null) v.x = x; if (y != null) v.y = y; if (zoom != null) v.lz = Math.log(zoom); if (rot != null) v.r = rot;
      if (dur <= 0) this.S.tl.set(this.p, v, at); else this.S.tl.to(this.p, { ...v, duration: dur, ease }, at);
      return this;
    }
    set(at, o) { return this.to(at, o, 0); }
    /** Frame a world rect (x,y,w,h) with padding (fraction of the stage). */
    frame(at, r, dur = 0.8, { pad = 0.12, ease, maxZoom = 4 } = {}) {
      const zoom = Math.min(maxZoom, (W * (1 - pad * 2)) / r.w, (H * (1 - pad * 2)) / r.h);
      return this.to(at, { x: r.x + r.w / 2, y: r.y + r.h / 2, zoom }, dur, ease);
    }
  }

  /* ---------- fake cursor ---------- */
  const CURSOR_SVG = '<svg viewBox="0 0 28 28" width="28" height="28"><path d="M5 3 L5 22 L10 17.5 L13.6 25.2 L17 23.7 L13.5 16.2 L20 16.2 Z" fill="#19191B" stroke="#fff" stroke-width="1.8" stroke-linejoin="round"/></svg>';
  class Cursor {
    constructor(S, o = {}) {
      this.S = S;
      this.el = el('div', { cls: 'f-cursor', parent: o.parent || S.world, html: CURSOR_SVG });
      this.ring = el('div', { cls: 'f-cursor-ring', parent: this.el });
      this.x = o.x ?? W * 0.7; this.y = o.y ?? H * 0.8;
      gsap.set(this.el, { x: this.x, y: this.y, scale: o.scale ?? 1, autoAlpha: o.hidden === false ? 1 : 0 });
      gsap.set(this.ring, { scale: 0, autoAlpha: 0 });
    }
    show(at, dur = 0.2) { this.S.tl.to(this.el, { autoAlpha: 1, duration: dur }, at); return this; }
    hide(at, dur = 0.2) { this.S.tl.to(this.el, { autoAlpha: 0, duration: dur }, at); return this; }
    /** Glide the arrow tip to world (x,y). */
    moveTo(at, x, y, dur = 0.6, ease = 'power2.inOut') { this.S.tl.to(this.el, { x, y, duration: dur, ease }, at); this.x = x; this.y = y; return this; }
    click(at, { sfx = true } = {}) {
      const tl = this.S.tl;
      tl.to(this.el, { scale: 0.86, duration: 0.07, ease: 'power2.out' }, at).to(this.el, { scale: 1, duration: 0.16, ease: 'back.out(3)' }, at + 0.07);
      tl.set(this.ring, { scale: 0.2, autoAlpha: 0.9 }, at).to(this.ring, { scale: 1.6, autoAlpha: 0, duration: 0.45, ease: 'power2.out' }, at);
      if (sfx) this.S.sfx(at, 'click');
      return this;
    }
  }

  /* ---------- scene ---------- */
  class Scene {
    constructor(def, spec) {
      Object.assign(this, { id: spec.id, start: spec.start, end: spec.end, dur: spec.end - spec.start, spec });
      this.root = el('div', { cls: 'f-scene', parent: scenesLayer, attrs: { 'data-scene': spec.id } });
      this.bg = el('div', { cls: 'f-scene-bg', parent: this.root });
      this.world = el('div', { cls: 'f-world', parent: this.root });
      this.overlay = el('div', { cls: 'f-overlay', parent: this.root });
      this.tl = gsap.timeline();
      this.camera = new Camera(this);
      this.def = def;
    }
    local(t) { return t - this.start; }
    vo(id) { const v = F.vo(id); return { t0: v.start - this.start, t1: v.end - this.start, text: v.text, words: v.words }; }
    word(id, key, nth = 1) { return F.word(id, key, nth, 't0') - this.start; }
    wordEnd(id, key, nth = 1) { return F.word(id, key, nth, 't1') - this.start; }
    el(tag, o = {}) { return el(tag, { parent: this.world, ...o }); }
    plate(name, state, o) { return new Plate(this, name, state, o); }
    seq(name, seqName, o) { return new Seq(this, name, seqName, o); }
    cursor(o) { return new Cursor(this, o); }
    mascot(variant, o = {}) {
      if (!window.Mascot) { violation('mascot.js not loaded'); return null; }
      return window.Mascot.create({ tl: this.tl, cue: (at, name, opt) => this.sfx(at, name, opt), parent: o.parent || this.world, variant, ...o });
    }
    sfx(at, name, o) { F.sfxAt(this.start + at, name, o); }
    onFrame(fn) { F.hooks.push((t) => fn(t - this.start, t)); }
    /** Top-centre black pill caption (overlay; unaffected by the camera). */
    caption(at, text, { dur = 2.2, y = 64, sfx = 'blip' } = {}) {
      const pill = el('div', { cls: 'f-caption', parent: this.overlay, html: text, style: { top: y + 'px' } });
      const tl = this.tl;
      tl.set(pill, { autoAlpha: 0, y: -14, scale: 0.92, xPercent: -50 }, 0);
      tl.to(pill, { autoAlpha: 1, y: 0, scale: 1, duration: 0.32, ease: 'back.out(2.2)' }, at);
      tl.to(pill, { autoAlpha: 0, y: -10, scale: 0.96, duration: 0.22, ease: 'power2.in' }, at + dur);
      if (sfx) this.sfx(at, sfx, { gain: 0.5 });
      return pill;
    }
    /** Full-stage chapter card: "01" chip + headline words rise in, hold, then the card slides away upward. */
    chapter(at, { num, title, dur = 1.5 } = {}) {
      const ch = this.spec.chapter || {}; num = num ?? ch.num; title = title ?? ch.title;
      const card = el('div', { cls: 'f-chapter', parent: this.overlay });
      el('div', { cls: 'f-chapter-num', parent: card, text: num });
      const h = el('div', { cls: 'f-chapter-title', parent: card });
      const words = String(title).split(' ').map((w) => el('span', { cls: 'f-chapter-word', parent: h, html: `<span>${w}</span>` }).firstChild);
      const tl = this.tl;
      tl.set(card, { yPercent: 0, autoAlpha: 0 }, 0);
      tl.set(card.firstChild, { y: 16, autoAlpha: 0.35 }, 0);
      tl.set(words, { yPercent: 62 }, 0);
      tl.set(card, { autoAlpha: 1 }, at);
      tl.fromTo(card.firstChild, { y: 16, autoAlpha: 0.35 }, { y: 0, autoAlpha: 1, duration: 0.3, ease: 'back.out(2)', immediateRender: false }, at);
      tl.fromTo(words, { yPercent: 62 }, { yPercent: 0, duration: 0.36, ease: 'power4.out', stagger: 0.05, immediateRender: false }, at);   // pre-risen: frame 0 is never bare paper
      tl.fromTo(h, { scale: 1 }, { scale: 1.045, duration: dur + 0.5, ease: 'none', immediateRender: false }, at);   // never a frozen hold
      tl.to(card, { yPercent: -100, duration: 0.5, ease: 'power3.in' }, at + dur);
      tl.set(card, { autoAlpha: 0 }, at + dur + 0.5);
      this.sfx(at, 'swoosh-up', { gain: 0.7 });
      return card;
    }
    /** Scene entrance/exit on the scene root. kinds: cut | fade | zoom | slide-left | slide-up | iris | drop */
    enter(kind = 'cut', { at = 0, dur = 0.45 } = {}) {
      const tl = this.tl, r = this.root;
      if (kind === 'fade') tl.fromTo(r, { opacity: 0 }, { opacity: 1, duration: dur, immediateRender: false }, at);
      else if (kind === 'zoom') tl.fromTo(r, { scale: 1.18, opacity: 0 }, { scale: 1, opacity: 1, duration: dur, ease: 'power3.out', immediateRender: false }, at);
      else if (kind === 'slide-left') tl.fromTo(r, { xPercent: 100 }, { xPercent: 0, duration: dur, ease: 'power3.out', immediateRender: false }, at);
      else if (kind === 'slide-up') tl.fromTo(r, { yPercent: 100 }, { yPercent: 0, duration: dur, ease: 'power3.out', immediateRender: false }, at);
      else if (kind === 'iris') tl.fromTo(r, { clipPath: 'circle(0.1px at 50% 50%)' }, { clipPath: 'circle(75% at 50% 50%)', duration: dur, ease: 'power2.inOut', immediateRender: false }, at);
      else if (kind === 'drop') tl.fromTo(r, { yPercent: -100 }, { yPercent: 0, duration: dur, ease: 'bounce.out', immediateRender: false }, at);
      if (kind !== 'cut') this.sfx(at, kind === 'drop' ? 'thud' : 'whoosh', { gain: 0.6 });
      return this;
    }
    exit(kind = 'cut', { dur = 0.4 } = {}) {
      const at = this.dur - dur, tl = this.tl, r = this.root;
      if (kind === 'fade') tl.to(r, { opacity: 0, duration: dur }, at);
      else if (kind === 'zoom') tl.to(r, { scale: 1.25, opacity: 0, duration: dur, ease: 'power3.in' }, at);
      else if (kind === 'slide-left') tl.to(r, { xPercent: -100, duration: dur, ease: 'power3.in' }, at);
      else if (kind === 'slide-up') tl.to(r, { yPercent: -100, duration: dur, ease: 'power3.in' }, at);
      else if (kind === 'iris') tl.to(r, { clipPath: 'circle(0.1px at 50% 50%)', duration: dur, ease: 'power2.inOut' }, at);
      return this;
    }
  }
  F.Scene = Scene;

  /* ---------- registration + build ---------- */
  const defs = [];
  /** Register a scene: F.scene({ id, build(S) }). Timing comes from the timeline (FILM_DATA.layout.scenes). */
  F.scene = (def) => defs.push(def);

  F.build = function () {
    for (const spec of D.layout.scenes) {
      const def = defs.find((d) => d.id === spec.id);
      const S = new Scene(def, spec);
      F.scenes.push(S);
      if (!def) {
        // placeholder until the scene file exists
        el('div', { cls: 'f-placeholder', parent: S.world, html: `<b>${spec.id}</b><br>${spec.start.toFixed(1)}–${spec.end.toFixed(1)} s` });
        if (spec.chapter) S.chapter(0.05);
      } else {
        try { def.build(S); } catch (e) { violation(`scene ${spec.id} build failed: ${e.stack || e}`); }
      }
      if (S.tl.duration() > S.dur + 0.001) violation(`scene ${spec.id} timeline runs ${S.tl.duration().toFixed(2)}s > its ${S.dur.toFixed(2)}s window`);
      F.master.add(S.tl, spec.start);
      // display:none (not visibility) for inactive scenes: a child's own visibility:visible can't leak through.
      // Set after build so scene builds can still measure their DOM.
      gsap.set(S.root, { display: 'none' });
      F.master.set(S.root, { display: 'block' }, spec.start);
      F.master.set(S.root, { display: 'none' }, spec.end);
    }
    // keep the master exactly the film's length
    F.master.set({}, {}, F.DUR);
    for (const d of defs) if (!D.layout.scenes.find((s) => s.id === d.id)) violation('scene file for unknown id ' + d.id);
    F.cues.sort((a, b) => a.t - b.t);
    // Prime: render the whole film once forward and back, so every tween records its start values in timeline
    // order now — a worker that first seeks to t=100 then renders exactly what continuous playback would.
    F.master.progress(1, true).progress(0, true);
  };

  /** The one clock: render film time t (seconds), run frame hooks. Returns a promise that resolves once images decoded. */
  F.seek = function (t) {
    t = Math.max(0, Math.min(F.DUR, t));
    F.t = t;
    // +1 µs: a seek that lands exactly on a scene's start (from a later time) would otherwise revert that scene's
    // zero-time set()s (GSAP renders zero-duration tweens at their own start as "before" when moving backwards).
    F.master.totalTime(Math.min(F.DUR, t + 1e-6), false);
    for (const h of F.hooks) h(t);
    return F.pending.size ? Promise.all([...F.pending]) : Promise.resolve();
  };
})();
