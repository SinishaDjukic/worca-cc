/** → { start, text } for one piece. Rules are matched at a line start (no partial-selector hits). */
export function cutPiece(css, piece) {
  if (piece.rule) {
    const re = new RegExp(`(^|\\n)${piece.rule.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
    const m = re.exec(css);
    if (!m) throw new Error(`style.css: rule not found (${piece.name}): ${piece.rule}`);
    const start = m.index + m[1].length;
    let depth = 0;
    for (let i = start; i < css.length; i++) {
      if (css[i] === '{') depth += 1;
      else if (css[i] === '}') { depth -= 1; if (depth === 0) return { start, text: `${css.slice(start, i + 1)}\n` }; }
    }
    throw new Error(`style.css: unbalanced rule (${piece.name})`);
  }
  const a = css.indexOf(piece.from);
  if (a < 0) throw new Error(`style.css: section marker not found (${piece.name}): ${piece.from}`);
  const b = css.indexOf(piece.to, a + piece.from.length);
  if (b < 0) throw new Error(`style.css: end marker not found (${piece.name}): ${piece.to}`);
  return { start: a, text: css.slice(a, b) };
}

const inSourceOrder = (css, pieces) => pieces.map((p) => cutPiece(css, p)).sort((x, y) => x.start - y.start).map((c) => c.text).join('');

/** name -> value of every custom property in the FIRST :root{…} block (it closes on its own line). */
export function tokenMap(css) {
  const a = css.indexOf(':root{');
  const body = css.slice(a + 6, css.indexOf('\n}', a));
  const out = {};
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

/** Whether some selector in `css` names `.cls` (followed by a non-identifier char). */
export function hasRuleFor(css, cls) {
  const re = new RegExp(`\\.${cls.replace(/[-]/g, '\\-')}(?![\\w-])[^{}]*\\{`);
  return re.test(css.replace(/\/\*[\s\S]*?\*\//g, ''));
}

const banner = '/* Generated by tools/build-extension.mjs from ui/public/style.css — do not edit. */\n';

export function sidebarCss(style, own) {
  return `${banner}[hidden]:not([hidden="until-found"]) { display: none !important; }\n${inSourceOrder(style, SIDEBAR_PIECES)}\n${own}`;
}

/** Tokens re-scoped to the shadow host; fonts are registered by the content script as "Worca Poppins" etc. (D15). */
export function toShadowTokens(tokens) {
  return tokens
    .replace(/@media print\{:root\{[^}]*\}\}/g, '')
    .replace(/:root\[data-theme="(light|dark)"\]/g, ':host([data-theme="$1"])')
    .replace(/:root\{/g, ':host{')
    .replace(/'Poppins'/g, "'Worca Poppins','Poppins'")
    .replace(/'JetBrains Mono'/g, "'Worca JetBrains Mono','JetBrains Mono'");
}

/** The shadow root's CSS. `own` (shadow.css, with :host{all:initial}) comes FIRST so the generated :host token block —
 *  which carries color-scheme:light dark — is never reset by `all`. */
export function shadowCss(style, own) {
  const pieces = SHADOW_PIECES.map((p) => ({ p, c: cutPiece(style, p) })).sort((x, y) => x.c.start - y.c.start);
  const body = pieces.map(({ p, c }) => (p.name === 'tokens' ? toShadowTokens(c.text) : c.text)).join('');
  return `${banner}${own}\n${body}`;
}
